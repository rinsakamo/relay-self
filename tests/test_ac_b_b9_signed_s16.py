def test_externally_signed_failure_and_unavailable_not_converted_to_success():
    issued, supervisor, binding, consequence, issuer, _, _, key = (
        qualified_fixture()
    )
    failed = replace(
        consequence,
        status=WorldConsequenceStatus.FAILED,
        error="test-fixture-adapter-error",
    )
    undetermined = replace(
        consequence, status=WorldConsequenceStatus.UNDETERMINED,
    )
    gate = ExternalS16EvidenceGate(
        key, TrustedWorldEpoch(consequence.session_id, 0),
    )
    fail_interpretation = gate.qualify(
        issued, binding, failed, issuer.sign(failed),
    )
    unavailable_interpretation = gate.qualify(
        issued, binding, undetermined, issuer.sign(undetermined),
    )
    assert fail_interpretation.disposition is ActionOutcomeDisposition.UNKNOWN
    assert unavailable_interpretation.disposition is (
        ActionOutcomeDisposition.UNAVAILABLE
    )
    assert supervisor.get(issued.action_id).state is ActionState.ISSUED
