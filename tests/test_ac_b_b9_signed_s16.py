def test_json_exact_fields_duplicate_keys_and_bool_int_confusion():
    issued, _, binding, consequence, _, gate, receipt, _ = qualified_fixture()
    raw = serialize_signed_evidence(receipt)
    value = json.loads(raw)
    bad = (
        raw.replace('"event_id":', '"event_id":"fake","event_id":', 1),
        json.dumps({**value, "unknown": "value"}),
        json.dumps({k: v for k, v in value.items() if k != "mac"}),
    )
    for item in bad:
        with pytest.raises(UnqualifiedWorldEvidence):
            parse_signed_evidence(item)
    invalid_revision = replace(receipt, revision=True)
    with pytest.raises(UnqualifiedWorldEvidence, match="invalid revision"):
        gate.qualify(issued, binding, consequence, invalid_revision)
    invalid_sequence = replace(receipt, sequence=True)
    with pytest.raises(UnqualifiedWorldEvidence, match="invalid sequence"):
        gate.qualify(issued, binding, consequence, invalid_sequence)


