def provenance(name: str) -> Provenance:
    return Provenance("b9-offline-test", name)


def qualified_fixture():
    chain = issued_chain()
    issued = chain[-1]
    supervisor = chain[-2]
    binding = chain[-4]
    assert issued.state is ActionState.ISSUED
    command = build_mineflayer_command(issued, binding)
    consequence = asyncio.run(execute_mineflayer_command(
        successful_session(command), command,
        provenance=provenance("known-fake-world-consequence"),
    ))
    assert consequence.status is WorldConsequenceStatus.EXECUTED
    key = new_fixture_keys()
    issuer = OfflineS16SourceIssuer(key, consequence.session_id)
    epoch = TrustedWorldEpoch(consequence.session_id, 0)
    gate = ExternalS16EvidenceGate(key, epoch)
    signed = issuer.sign(consequence)
    return issued, supervisor, binding, consequence, issuer, gate, signed, key


def test_source_bound_full_s16_consequence_is_pure_read_only_interpretation():
    issued, supervisor, binding, consequence, issuer, gate, receipt, _ = (
        qualified_fixture()
    )
    assert consequence.before_observation is not None
    assert consequence.dispatch_receipt is not None
    assert consequence.cleanup_receipt is not None
    assert consequence.after_observation is not None
    assert consequence.movement_distance > 0
    assert issuer.session == consequence.session_id
    assert receipt.consequence_digest
    reloaded = parse_signed_evidence(serialize_signed_evidence(receipt))
    assert reloaded == receipt and reloaded is not receipt
    original = supervisor.get(issued.action_id)
    result = gate.qualify(issued, binding, consequence, reloaded)
    assert result.disposition is ActionOutcomeDisposition.OUTCOME
    assert result.reason_code == "observed_execution"
    assert result.source_status == WorldConsequenceStatus.EXECUTED.value
    assert result.provenance.reference == receipt.event_id
    assert result.world_provenance == consequence.provenance
    assert result.action_id == issued.action_id
    assert result.binding_id == binding.binding_id
    assert supervisor.get(issued.action_id) is original
    assert original.state is ActionState.ISSUED


def test_explicit_supervisor_outcome_and_s17_criterion_needed_for_feedback():
    issued, supervisor, binding, consequence, _, gate, receipt, _ = (
        qualified_fixture()
    )
    interpreted = gate.qualify(issued, binding, consequence, receipt)
    assert supervisor.get(issued.action_id).state is ActionState.ISSUED
    closed = record_interpreted_action_outcome(
        supervisor, interpreted, at_ns=20,
    )
    assert closed.state is ActionState.OUTCOME
    no_criterion = None
    assert no_criterion is None  # no implicit criterion generated by gate
    real = interpret_action_outcome_as_learning_feedback(
        closed, interpreted, feedback_criterion(),
        provenance=provenance("only-explicit-criterion"),
    )
    assert real.status is LearningFeedbackInterpretationStatus.PRODUCED
    assert real.feedback is not None
    assert real.feedback.consequence_ref == real.outcome_ref
    assert real.world_provenance == interpreted.world_provenance
    mismatched = interpret_action_outcome_as_learning_feedback(
        closed, interpreted, feedback_criterion(reason="wrong_reason"),
        provenance=provenance("mismatched-criterion"),
    )
    assert mismatched.status is LearningFeedbackInterpretationStatus.NOT_APPLICABLE
    assert mismatched.feedback is None
    state = learning_state()
    proposal = propose_learning_update(state, real.feedback, learning_rule())
    assert proposal.proposed_value == 4 and state.value == 3
    with pytest.raises(MissingLearningAuthority):
        commit_learning_update(
            state, proposal, None,
            provenance=provenance("no-s10-commit-authority"),
        )
    assert state.value == 3 and state.revision == 0


