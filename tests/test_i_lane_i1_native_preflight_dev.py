def test_i1_failed_partial_native_cleanup_closes_outbound_transcript():
    class Native:
        process_returncode = 0
        _raw_source_audit_finished = False
        _raw_command_audit_fd = 1

        def finish_raw_source_audit(self):
            self._raw_source_audit_finished = True

        def finish_raw_command_audit(self):
            self._raw_command_audit_fd = None

    report = {}
    native = Native()
    asyncio.run(runner._cleanup_native(native, report))
    assert native._raw_source_audit_finished
    assert native._raw_command_audit_fd is None
    assert not report


