@pytest.mark.skipif(not shutil.which("node"), reason="native Node CLI not installed")
def test_i1_real_node_punycode_warning_is_captured_if_emitted(local_native):
    # Node 22 runtime warning is generated by a source dependency,
    # not fake Python stderr; no createBot call, no process masking.
    entry = local_native / "node_modules" / "mineflayer" / "index.js"
    entry.write_text("require('punycode');\n" + entry.read_text(), encoding="utf-8")
    receipt = require_i1_native_preflight(node="node", bridge_dir=local_native)
    # Some CI Node configurations emit no runtime diagnostic. Either way,
    # any nonempty original stderr must meet the exact DEP0040 classifier;
    # no warning is manufactured for a genuinely quiet runtime.
    assert receipt.node_module_warning_code in (None, "DEP0040")
    if receipt.node_module_warning_code == "DEP0040":
        assert "[DEP0040] DeprecationWarning" in receipt.node_module_stderr_raw
        assert "node --trace-deprecation" in receipt.node_module_stderr_raw
    else:
        assert receipt.node_module_stderr_raw == ""
    assert receipt.node_module_stderr_sha256 == hashlib.sha256(
        receipt.node_module_stderr_raw.encode("utf-8")
    ).hexdigest()
    assert receipt.world_started is False


@pytest.mark.parametrize("kind", [
    "linked-node-modules", "linked-package-directory", "linked-source",
    "missing-source", "unpatched-source", "unsupported-version",
    "missing-module-entry", "broken-module-entry", "malformed-module-api",
])
def test_i1_preflight_rejects_bad_real_dependency_tree_before_world(
    local_native, tmp_path, kind, monkeypatch,
):
    source = local_native / "node_modules" / "mineflayer" / "lib" / "plugins" / "entities.js"
    manifest = local_native / "node_modules" / "mineflayer" / "package.json"
    if kind == "linked-node-modules":
        directory = local_native / "node_modules"
        relocated = tmp_path / "borrowed-node-modules"
        directory.rename(relocated)
        directory.symlink_to(relocated, target_is_directory=True)
    elif kind == "linked-package-directory":
        directory = local_native / "node_modules" / "mineflayer"
        relocated = tmp_path / "borrowed-mineflayer"
        directory.rename(relocated)
        directory.symlink_to(relocated, target_is_directory=True)
    elif kind == "linked-source":
        relocated = tmp_path / "borrowed-entities.js"
        source.rename(relocated)
        source.symlink_to(relocated)
    elif kind == "missing-source":
        source.unlink()
    elif kind == "missing-module-entry":
        (local_native / "node_modules" / "mineflayer" / "index.js").unlink()
    elif kind == "broken-module-entry":
        (local_native / "node_modules" / "mineflayer" / "index.js").write_text(
            "require('not-installed-transitive-package');\n", encoding="utf-8",
        )
    elif kind == "malformed-module-api":
        (local_native / "node_modules" / "mineflayer" / "index.js").write_text(
            "module.exports = {createBot: 12};\n", encoding="utf-8",
        )
    elif kind == "unpatched-source":
        source.write_text(source.read_text().replace(
            "metas.air_supply != null && entity.id === bot.entity?.id",
            "metas.air_supply != null",
        ), encoding="utf-8")
    else:
        manifest.write_text('{"version":"4.40.0"}\n', encoding="utf-8")

    if kind.startswith("linked") or kind == "missing-source":
        # A symlinked source must HOLD at the Python path fence, before even
        # launching the read-only Node inspector.
        monkeypatch.setattr(
            "relay_self.i_lane_i1_native_preflight_dev.subprocess.run",
            lambda *_args, **_kw: pytest.fail("Node inspector invoked after invalid path"),
        )
    with pytest.raises(I1NativePreflightHold):
        require_i1_native_preflight(node="node", bridge_dir=local_native)


